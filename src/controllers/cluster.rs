    // ── Managed coordination Secret (create-once) ──────────────

    fn bytes(m: &BTreeMap<String, ByteString>, k: &str) -> Vec<u8> {
        m.get(k).expect("key present").0.clone()
    }

    #[test]
    fn coordination_data_generates_token_and_state_key() {
        let data = merge_coordination_data(BTreeMap::new(), None);
        let token = bytes(&data, MANAGED_NATS_TOKEN_ENV);
        let state = bytes(&data, MANAGED_STATE_KEY_ENV);
        assert!(!token.is_empty());
        assert!(!state.is_empty());
        assert_ne!(token, state, "token and state key must be distinct");
        // No CA on the plaintext path.
        assert!(!data.contains_key(MANAGED_NATS_CA_ENV));
        // State key decodes back to exactly 32 bytes (the gateway loader's
        // requirement) — 32 random bytes as URL-safe base64.
        let decoded = base64::engine::general_purpose::URL_SAFE_NO_PAD
            .decode(&state)
            .expect("state key is url-safe base64");
        assert_eq!(decoded.len(), 32);
    }

    #[test]
    fn coordination_data_is_create_once_on_re_reconcile() {
        // First reconcile mints the material…
        let first = merge_coordination_data(BTreeMap::new(), None);
        let token = bytes(&first, MANAGED_NATS_TOKEN_ENV);
        let state = bytes(&first, MANAGED_STATE_KEY_ENV);
        // …a second reconcile with the existing data preserves it verbatim
        // (a rotation would orphan every sealed record).
        let second = merge_coordination_data(first.clone(), None);
        assert_eq!(bytes(&second, MANAGED_NATS_TOKEN_ENV), token);
        assert_eq!(bytes(&second, MANAGED_STATE_KEY_ENV), state);
    }

    #[test]
    fn coordination_data_syncs_and_drops_ca() {
        // TLS path: CA folded in, token/state preserved.
        let base = merge_coordination_data(BTreeMap::new(), None);
        let with_ca =
            merge_coordination_data(base.clone(), Some("-----BEGIN CERTIFICATE-----\nX\n"));
        assert_eq!(
            bytes(&with_ca, MANAGED_NATS_CA_ENV),
            b"-----BEGIN CERTIFICATE-----\nX\n".to_vec()
        );
        assert_eq!(
            bytes(&with_ca, MANAGED_NATS_TOKEN_ENV),
            bytes(&base, MANAGED_NATS_TOKEN_ENV),
            "CA sync must not rotate the token"
        );
        // Turning TLS off removes the CA (but keeps token/state).
        let without_ca = merge_coordination_data(with_ca, None);
        assert!(!without_ca.contains_key(MANAGED_NATS_CA_ENV));
        assert_eq!(
            bytes(&without_ca, MANAGED_NATS_TOKEN_ENV),
            bytes(&base, MANAGED_NATS_TOKEN_ENV)
        );
    }

    #[test]
    fn generated_keys_are_url_safe_unpadded() {
        let k = gen_url_safe_key(32);
        assert_eq!(k.len(), 43, "32 bytes → 43 unpadded base64url chars");
        assert!(!k.contains('='), "unpadded");
        assert!(
            k.chars()
                .all(|c| c.is_ascii_alphanumeric() || c == '-' || c == '_'),
            "url-safe alphabet only: {k}"
        );
    }
