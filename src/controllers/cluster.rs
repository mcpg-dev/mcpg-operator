//! `MCPGCluster` controller — validates a cluster-coordination
//! backend binding, reports its bindability + blast radius, and (for a
//! `managed` coordinator) PROVISIONS the NATS backend itself.
//!
//! ## Point-at-existing (non-managed) clusters
//!
//! The controller synthesises **no** child objects: a cluster binding is
//! consumed gateway-side (the gateway controller resolves `clusterRef`,
//! renders the backend's `cluster:` block into the gateway config, and
//! folds the cluster's `configHash` into its pod-roll trigger). The job
//! is to resolve `spec.backend` → cdylib id, gate on `spec.pluginRef`
//! readiness when set, compute the config hash + bound-gateway count, and
//! surface a `Ready` condition.
//!
//! ## Managed clusters (`spec.managed`)
//!
//! When a coordinator is managed the controller additionally renders and
//! owns, in the operator namespace: a **NATS StatefulSet** (JetStream
//! file store on a `volumeClaimTemplate`), a **headless + client
//! Service**, a **ConfigMap** (`nats-server.conf`), a **generated
//! coordination Secret** (NATS token and state-encryption key,
//! create-once, plus the CA on the TLS path), and — with
//! `managed.tls.issuerRef` — a cert-manager **Certificate**. These live
//! under a cluster-scoped parent
//! in a namespace, so — matching `controllers::plugin` — they carry no
//! cross-scope owner ref and are pruned by label on deletion. The rendered
//! `cluster:` block (generated by `render_managed_cluster_block`) points
//! bound gateways at the client Service; the gateway controller copies the
//! coordination Secret into each bound gateway's namespace and projects it
//! via `envFrom` (token + state key [+ CA]).

